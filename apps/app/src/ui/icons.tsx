export type IconName = keyof typeof registry;

/** Einheitliche Symbolgrößen (pro-rules: Größen als Tokens). */
export const iconSize = { sm: 16, md: 20, lg: 24, xl: 32 } as const;

export function isIconName(name: string): name is IconName {
  return name in registry;
}

export function Icon({ name, size = iconSize.md, color }: { name: IconName | string; size?: number; color: string }) {
  const Component: ComponentType<IconProps> = isIconName(name) ? registry[name] : CircleIcon;
  // Symbole neben Text sind dekorativ und für Screenreader ausgeblendet;
  // zugängliche Namen tragen die Bedienelemente selbst.
  return (
    <View aria-hidden accessibilityElementsHidden importantForAccessibility="no-hide-descendants" style={{ width: size, height: size }}>
      <Component size={size} color={color} weight="regular" />
    </View>
  );
}
